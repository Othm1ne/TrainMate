import { onCall } from "firebase-functions/v2/https";
import { FieldValue, Timestamp } from "firebase-admin/firestore";
import { db, region } from "../bootstrap";
import {
  BOOST_DAYS, CATEGORIES, CONDITIONS, FREE_ACTIVE_LISTINGS, FREE_BOOSTS_PER_MONTH_PREMIUM,
  LISTING_TTL_DAYS, LIVE_STATUSES, MAX_PHOTOS, MODES, SPORTS,
} from "./constants";
import { moderationFlags } from "./moderation";
import {
  check, getUserData, inDays, money, notify, now, oneOf, optStr, ownedPhotoUrls,
  publicInfo, requireUid, storeChatId, str,
} from "./common";

/**
 * Creates or updates a listing. All listing writes go through here so the
 * server can enforce verification (rent), limits, moderation and pricing.
 * data.id: a Firestore auto-id generated by the client (photos are uploaded
 * under listings/{uid}/{id}/ before calling).
 */
export const saveListing = onCall({ region }, async (req) => {
  const uid = requireUid(req);
  const d = req.data ?? {};
  const id = str(d.id, "id", 10, 40);
  check(/^[A-Za-z0-9]+$/.test(id), "Invalid id.");

  const user = await getUserData(uid);
  check(user.storeSuspended !== true, "Your store access is suspended.", "permission-denied");

  const mode = oneOf(d.mode, MODES, "mode");
  const renting = mode !== "sale";
  const selling = mode !== "rent";
  check(!renting || user.verified === true,
    "Only verified users can rent out equipment. Get verified first.", "failed-precondition");

  const minDays = renting ? Number(d.minDays ?? 1) : 1;
  const maxDays = renting ? Number(d.maxDays ?? 14) : 14;
  check(Number.isInteger(minDays) && Number.isInteger(maxDays) &&
    minDays >= 1 && maxDays >= minDays && maxDays <= 90, "Invalid rental duration.");

  const canShip = selling && d.canShip === true;
  const fields = {
    title: str(d.title, "Title", 5, 80),
    description: str(d.description, "Description", 20, 2000),
    sport: oneOf(d.sport, SPORTS, "sport"),
    category: oneOf(d.category, CATEGORIES, "category"),
    condition: oneOf(d.condition, CONDITIONS, "condition"),
    brand: optStr(d.brand, 60),
    size: optStr(d.size, 30),
    mode,
    salePrice: money(d.salePrice, "Sale price", selling),
    rentPerDay: money(d.rentPerDay, "Price per day", renting),
    rentPerWeekend: renting ? money(d.rentPerWeekend, "Weekend price", false) : null,
    rentPerWeek: renting ? money(d.rentPerWeek, "Week price", false) : null,
    // TODO(deposit): accept and validate a deposit amount once in-app payments exist (V3).
    deposit: null,
    minDays,
    maxDays,
    canShip,
    shippingPrice: canShip ? money(d.shippingPrice, "Shipping price", true) : null,
    photos: ownedPhotoUrls(d.photos, `listings/${uid}/${id}/`, 1, MAX_PHOTOS),
    area: str(d.area ?? user.location ?? "", "Pickup area", 2, 60),
    // Profile coordinates are already rounded to ~1 km.
    lat: (user.lat as number) ?? null,
    lng: (user.lng as number) ?? null,
  };

  const pro = user.shopStatus === "approved" && typeof user.shopId === "string";
  const ref = db.doc(`listings/${id}`);
  const flags = moderationFlags(fields);

  return db.runTransaction(async (tx) => {
    const snap = await tx.get(ref);
    const existing = snap.data();
    if (existing) {
      check(existing.ownerId === uid, "Not your listing.", "permission-denied");
      check(!["sold", "removed"].includes(existing.status), "This listing is closed.", "failed-precondition");
    } else if (!pro && user.isPremium !== true) {
      const live = await tx.get(db.collection("listings")
        .where("ownerId", "==", uid).where("status", "in", LIVE_STATUSES));
      check(live.size < FREE_ACTIVE_LISTINGS,
        `Free accounts can have ${FREE_ACTIVE_LISTINGS} active listings. Go Premium for unlimited.`,
        "failed-precondition");
    }

    // Flagged → held for review. Otherwise keep the owner's pause/reserve
    // state, and (re)activate anything new, held or expired.
    const prev = existing?.status as string | undefined;
    const status = flags.length ? "pending_review" :
      prev === "paused" || prev === "reserved" ? prev : "active";

    tx.set(ref, {
      ...fields,
      ownerId: uid,
      ownerInfo: publicInfo(user),
      sellerType: pro ? "pro" : "private",
      shopId: pro ? user.shopId : null,
      status,
      moderationFlags: flags,
      expiresAt: inDays(LISTING_TTL_DAYS),
      updatedAt: now(),
      ...(existing ? {} : { createdAt: now(), views: 0, boostedUntil: null }),
    }, { merge: true });
    return { id, status, flags };
  });
});

/** Owner actions that don't change content. */
export const setListingStatus = onCall({ region }, async (req) => {
  const uid = requireUid(req);
  const id = str(req.data?.listingId, "listingId", 10, 40);
  const action = oneOf(req.data?.action, ["pause", "resume", "reserve", "unreserve", "delete"] as const, "action");
  const ref = db.doc(`listings/${id}`);
  const l = (await ref.get()).data();
  check(l, "Listing not found.", "not-found");
  check(l.ownerId === uid, "Not your listing.", "permission-denied");

  const from: Record<typeof action, string[]> = {
    pause: ["active", "reserved"],
    resume: ["paused", "expired"],
    reserve: ["active"],
    unreserve: ["reserved"],
    delete: ["active", "paused", "reserved", "pending_review", "expired"],
  };
  check(from[action].includes(l.status), "Not possible in the current state.", "failed-precondition");
  const to = { pause: "paused", resume: "active", reserve: "reserved", unreserve: "active", delete: "removed" }[action];
  await ref.update({
    status: to,
    updatedAt: now(),
    ...(action === "resume" ? { expiresAt: inDays(LISTING_TTL_DAYS) } : {}),
  });
  return { status: to };
});

/**
 * Pins a listing to the top of search for 7 days.
 * TODO(payments): charge BOOST_PRICE_EUR via in-app purchase / RevenueCat
 * (verify a receipt here). Until then boosts are granted for free, using a
 * Premium user's monthly free boosts first.
 */
export const boostListing = onCall({ region }, async (req) => {
  const uid = requireUid(req);
  const id = str(req.data?.listingId, "listingId", 10, 40);
  const listingRef = db.doc(`listings/${id}`);
  const userRef = db.doc(`users/${uid}`);
  const month = new Date().toISOString().slice(0, 7);

  return db.runTransaction(async (tx) => {
    const [l, u] = [(await tx.get(listingRef)).data(), (await tx.get(userRef)).data()];
    check(l && u, "Not found.", "not-found");
    check(l.ownerId === uid, "Not your listing.", "permission-denied");
    check(l.status === "active", "Only active listings can be boosted.", "failed-precondition");

    const used = u.boostMonth === month ? (u.freeBoostsUsed ?? 0) : 0;
    const free = u.isPremium === true && used < FREE_BOOSTS_PER_MONTH_PREMIUM;
    if (free) tx.update(userRef, { boostMonth: month, freeBoostsUsed: used + 1 });

    const current = (l.boostedUntil as Timestamp | null)?.toMillis() ?? 0;
    const until = Timestamp.fromMillis(Math.max(Date.now(), current) + BOOST_DAYS * 86400000);
    tx.update(listingRef, { boostedUntil: until });
    return { free, boostedUntil: until.toMillis() };
  });
});

/** Opens (or reuses) the chat between a customer and the listing's owner. */
export const contactOwner = onCall({ region }, async (req) => {
  const uid = requireUid(req);
  const id = str(req.data?.listingId, "listingId", 10, 40);
  const l = (await db.doc(`listings/${id}`).get()).data();
  check(l && ["active", "reserved"].includes(l.status), "This listing is not available.", "failed-precondition");
  check(l.ownerId !== uid, "This is your own listing.");
  return { chatId: await ensureStoreChat(id, l, uid, `Interested in "${l.title}"`) };
});

/** Creates the store chat if needed; returns its id. */
export async function ensureStoreChat(
  listingId: string, listing: FirebaseFirestore.DocumentData, customerUid: string, preview: string,
): Promise<string> {
  const [owner, customer] = await Promise.all([
    getUserData(listing.ownerId), getUserData(customerUid),
  ]);
  check(!(owner.blocked ?? []).includes(customerUid) && !(customer.blocked ?? []).includes(listing.ownerId),
    "You can't contact this user.", "permission-denied");

  const chatId = storeChatId(listingId, customerUid);
  const ref = db.doc(`chats/${chatId}`);
  await db.runTransaction(async (tx) => {
    if ((await tx.get(ref)).exists) return;
    tx.set(ref, {
      kind: "store",
      listingId,
      listingInfo: { title: listing.title, cover: listing.photos?.[0] ?? "" },
      members: [listing.ownerId, customerUid],
      memberInfo: {
        [listing.ownerId]: { name: owner.name ?? "", photoUrl: owner.photoUrl ?? "" },
        [customerUid]: { name: customer.name ?? "", photoUrl: customer.photoUrl ?? "" },
      },
      lastMessage: preview,
      lastTime: FieldValue.serverTimestamp(),
      mutedBy: [],
      blockedBy: [],
    });
  });
  return chatId;
}

/** Marks a listing as sold to someone who contacted the seller about it. */
export const markSold = onCall({ region }, async (req) => {
  const uid = requireUid(req);
  const id = str(req.data?.listingId, "listingId", 10, 40);
  const buyerUid = str(req.data?.buyerUid, "buyerUid", 10, 128);
  const delivery = oneOf(req.data?.delivery, ["hand", "ship"] as const, "delivery");
  const listingRef = db.doc(`listings/${id}`);

  const saleId = await db.runTransaction(async (tx) => {
    const l = (await tx.get(listingRef)).data();
    check(l, "Listing not found.", "not-found");
    check(l.ownerId === uid, "Not your listing.", "permission-denied");
    check(l.mode !== "rent", "Rental-only listings can't be sold.", "failed-precondition");
    check(["active", "reserved", "paused"].includes(l.status), "Not possible in the current state.", "failed-precondition");
    check(delivery === "hand" || l.canShip, "This listing is hand delivery only.");
    const chat = await tx.get(db.doc(`chats/${storeChatId(id, buyerUid)}`));
    check(chat.exists, "The buyer must have contacted you about this listing.", "failed-precondition");

    const saleRef = db.collection("sales").doc();
    tx.set(saleRef, {
      listingId: id,
      sellerId: uid,
      buyerId: buyerUid,
      members: [uid, buyerUid],
      price: l.salePrice,
      delivery,
      listingSnapshot: { title: l.title, cover: l.photos?.[0] ?? "" },
      createdAt: now(),
      reviewDeadline: inDays(14),
    });
    tx.update(listingRef, { status: "sold", soldAt: now(), updatedAt: now() });
    return saleRef.id;
  });

  await notify(buyerUid, "Purchase recorded ✅", "How did it go? Leave a review for the seller.",
    { type: "review", context: "sale", refId: saleId });
  return { saleId };
});

/** Records a view (once per user per listing). */
export const viewListing = onCall({ region }, async (req) => {
  const uid = requireUid(req);
  const id = str(req.data?.listingId, "listingId", 10, 40);
  const viewRef = db.doc(`listings/${id}/views/${uid}`);
  await db.runTransaction(async (tx) => {
    const [v, l] = [await tx.get(viewRef), await tx.get(db.doc(`listings/${id}`))];
    if (v.exists || !l.exists || l.data()!.ownerId === uid) return;
    tx.set(viewRef, { at: now() });
    tx.update(l.ref, { views: FieldValue.increment(1) });
  });
  return { ok: true };
});
